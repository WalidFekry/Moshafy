    public static List<AzkarModel> getAzkarByCategory(Context context, int categoryType) {
        switch (categoryType) {
            case CATEGORY_MORNING:
                return getMorningAzkar(context);
            case CATEGORY_EVENING:
                return getEveningAzkar(context);
            case CATEGORY_RAMADAN:
                return getRamadanAzkar(context);
            case CATEGORY_SLEEP:
                return getSleepAzkar(context);
            case CATEGORY_WAKEUP:
                return getWakeUpAzkar(context);
            case CATEGORY_GENERAL:
            default:
                return getGeneralDuas(context);
        }
    }

